"""Results of the individual permutation test and proportion statistics.

The files are generated by examples/run_permutation_tests.py and read by
the two group scripts (run_group_npz_pp.py, run_group_npz_lg.py).

Statistical choices:
  - individual significance: permutation p-value,
    Benjamini–Hochberg correction applied to the ENTIRE set of subjects in the comparison, across all groups
    combined (a single family, similar to the ‘across subjects’ correction by
    King et al. 2013). A group-by-group correction would result in a
    that differs for each group – more permissive where there are many effects
    – and would render the proportions incomparable across groups;
  - proportion of significant subjects: exact 95% Clopper-Pearson CI;
  - comparison of proportions between two groups: two-sided exact Fisher’s test,
    Benjamini-Hochberg correction applied to pairs of groups.
"""
import glob
import logging
import os
from itertools import combinations

import numpy as np
from scipy.stats import fisher_exact
from statsmodels.stats.multitest import fdrcorrection
from statsmodels.stats.proportion import proportion_confint

logger = logging.getLogger(__name__)

PERMUTATION_SUBDIR = "permutation_tests"


def load_permutation_results(results_dir, paradigm, contrast):
    """{sujet: {'auc', 'p_value', 'n_folds', 'n_permutations'}} pour un contraste."""
    pattern = os.path.join(results_dir, PERMUTATION_SUBDIR, paradigm,
                           f"*_{contrast}.npz")
    results = {}
    for path in sorted(glob.glob(pattern)):
        try:
            with np.load(path, allow_pickle=False) as d:
                results[str(d["subject_id"])] = {
                    "auc": float(d["auc"]), "p_value": float(d["p_value"]),
                    "n_folds": int(d["n_folds"]),
                    "n_permutations": int(d["n_permutations"]),
                }
        except (OSError, KeyError, ValueError) as exc:
            logger.warning("Fichier de permutation illisible %s : %s", path, exc)
    folds = {r["n_folds"] for r in results.values()}
    if len(folds) > 1:
        logger.warning("%s/%s : nombres de plis differents %s.",
                       paradigm, contrast, sorted(folds))
    logger.info("%d resultats de permutation charges pour %s/%s (%s).",
                len(results), paradigm, contrast, pattern)
    return results


def attach_permutation_results(subject_ids, permutation_results):
    """AUC et p de permutation alignees sur subject_ids (NaN si absent)."""
    auc = np.array([permutation_results.get(s, {}).get("auc", np.nan)
                    for s in subject_ids], dtype=float)
    p = np.array([permutation_results.get(s, {}).get("p_value", np.nan)
                  for s in subject_ids], dtype=float)
    return auc, p


def proportion_statistics(groups, alpha=0.05):
    """Significativite individuelle et proportions par groupe.

    groups : {nom_groupe: (subject_ids, p_values)} ; p NaN = pas de resultat.
    """
    pooled = {}
    for ids, pvals in groups.values():
        for sid, p in zip(ids, pvals):
            if np.isfinite(p):
                pooled[sid] = float(p)   # un sujet present dans 2 groupes compte une fois
    if not pooled:
        return None

    sids = list(pooled)
    rejected, p_fdr = fdrcorrection(np.array([pooled[s] for s in sids]),
                                    alpha=alpha)
    subjects = {s: {"p": pooled[s], "p_fdr": float(q), "significant": bool(r)}
                for s, q, r in zip(sids, p_fdr, rejected)}

    group_stats = {}
    for name, (ids, pvals) in groups.items():
        tested = [s for s, p in zip(ids, pvals) if np.isfinite(p)]
        n = len(tested)
        k = sum(subjects[s]["significant"] for s in tested)
        lo, hi = proportion_confint(k, n, alpha=0.05, method="beta") if n else (np.nan, np.nan)
        group_stats[name] = {
            "n_tested": n, "n_significant": int(k),
            "proportion": k / n if n else np.nan,
            "ci95_clopper_pearson": [float(lo), float(hi)],
            "n_significant_uncorrected": int(sum(subjects[s]["p"] < alpha
                                                 for s in tested)),
            "missing": [s for s, p in zip(ids, pvals) if not np.isfinite(p)],
        }

    pairs = [(a, b) for a, b in combinations(group_stats, 2)
             if group_stats[a]["n_tested"] and group_stats[b]["n_tested"]]
    pairwise = []
    for a, b in pairs:
        ga, gb = group_stats[a], group_stats[b]
        table = [[ga["n_significant"], ga["n_tested"] - ga["n_significant"]],
                 [gb["n_significant"], gb["n_tested"] - gb["n_significant"]]]
        odds, p = fisher_exact(table, alternative="two-sided")
        pairwise.append({"group_1": a, "group_2": b, "table": table,
                         "odds_ratio": float(odds), "p": float(p)})
    if pairwise:
        rej, q = fdrcorrection([r["p"] for r in pairwise], alpha=alpha)
        for r, qi, ri in zip(pairwise, q, rej):
            r["p_fdr"], r["significant"] = float(qi), bool(ri)

    overlap = [s for s in pooled
               if sum(s in ids for ids, _ in groups.values()) > 1]
    if overlap:
        logger.warning("Sujets presents dans plusieurs groupes (comptes une "
                       "fois dans la correction, mais dans chaque groupe pour "
                       "les proportions et les tests de Fisher) : %s", overlap)

    return {
        "alpha": alpha,
        "correction": "Benjamini-Hochberg sur tous les sujets du contraste",
        "n_subjects_pooled": len(pooled),
        "subjects_in_several_groups": overlap,
        "subjects": subjects, "groups": group_stats,
        "pairwise_fisher": pairwise,
    }


def proportion_report(stats):
    """Resume texte (log) de proportion_statistics."""
    lines = [f"Significativite individuelle : permutation, {stats['correction']} "
             f"(n={stats['n_subjects_pooled']}, alpha={stats['alpha']})"]
    for name, g in stats["groups"].items():
        lo, hi = g["ci95_clopper_pearson"]
        lines.append(f"  {name:12s} {g['n_significant']:2d}/{g['n_tested']:2d} "
                     f"= {100 * g['proportion']:5.1f} %  IC95 [{100 * lo:.1f}-{100 * hi:.1f}]"
                     f"  (non corrige : {g['n_significant_uncorrected']})"
                     + (f"  manquants : {g['missing']}" if g["missing"] else ""))
    for r in stats["pairwise_fisher"]:
        lines.append(f"  Fisher {r['group_1']} vs {r['group_2']} : OR={r['odds_ratio']:.2f} "
                     f"p={r['p']:.4f} p_FDR={r['p_fdr']:.4f}{'  *' if r['significant'] else ''}")
    return "\n".join(lines)


def benjamini_hochberg(pvalues, alpha=0.05):
    """p corrigees BH ; les NaN restent NaN."""
    p = np.asarray(pvalues, dtype=float)
    out = np.full(p.shape, np.nan)
    ok = np.isfinite(p)
    if ok.any():
        out[ok] = fdrcorrection(p[ok], alpha=alpha)[1]
    return out


def stars(p):
    """Etoiles conventionnelles pour une p (corrigee)."""
    if not np.isfinite(p) or p >= 0.05:
        return ""
    return "***" if p < 0.001 else "**" if p < 0.01 else "*"


if __name__ == "__main__":
    # Verification minimale : 3 groupes, correction commune, Fisher.
    rng = np.random.default_rng(0)
    g = {"A": ([f"a{i}" for i in range(20)], np.r_[np.full(10, 1e-3), rng.uniform(0.2, 1, 10)]),
         "B": ([f"b{i}" for i in range(20)], rng.uniform(0.2, 1, 20)),
         "C": (["a0", "c1"], np.array([1e-3, np.nan]))}
    s = proportion_statistics(g)
    assert s["groups"]["A"]["n_significant"] == 10
    assert s["groups"]["B"]["n_significant"] == 0
    assert s["groups"]["C"]["missing"] == ["c1"] and s["groups"]["C"]["n_tested"] == 1
    assert s["n_subjects_pooled"] == 40 and s["subjects_in_several_groups"] == ["a0"]
    ab = next(r for r in s["pairwise_fisher"] if {r["group_1"], r["group_2"]} == {"A", "B"})
    assert ab["p"] < 0.001 and ab["significant"]
    lo, hi = s["groups"]["A"]["ci95_clopper_pearson"]
    assert 0.27 < lo < 0.28 and 0.72 < hi < 0.73, (lo, hi)
    assert stars(0.0004) == "***" and stars(0.2) == "" and stars(np.nan) == ""
    assert np.isnan(benjamini_hochberg([0.01, np.nan])[1])
    print("permutation_stats: OK")
